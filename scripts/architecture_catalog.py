#!/usr/bin/env python3
"""Generate and verify docs/adr/CATALOG.md & SOTA_WORKFLOW_MANIFEST.json ADR parity (MADR 4.0 + GitHub Evidence)."""

from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
from typing import Any

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
ADR_DIR = REPO_ROOT / "docs" / "adr"
CATALOG_PATH = ADR_DIR / "CATALOG.md"
MANIFEST_PATH = REPO_ROOT / "SOTA_WORKFLOW_MANIFEST.json"
REVISIT_DAYS = 45

REQUIRED_META = ("Status", "Date", "Layer", "Evidence Grade", "GitHub Evidence", "Revisit Trigger")
REQUIRED_SECTIONS = (
    "## Context and Problem Statement",
    "## Decision Outcome",
    "## Alternatives Considered",
    "## Verification Witness",
)
GITHUB_URL_RE = re.compile(r"https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+")


def parse_adr(path: pathlib.Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    m_title = re.search(r"^#\s+(ADR-\d{4}):\s+(.+)$", text, re.MULTILINE)
    if not m_title:
        raise ValueError(f"{path.name}: missing '# ADR-XXXX: Title'")
    adr_id = m_title.group(1)
    if not path.name.startswith(f"{adr_id}-"):
        raise ValueError(f"{path.name}: ID mismatch '{adr_id}'")
    meta: dict[str, Any] = {"id": adr_id, "title": m_title.group(2).strip(), "file": path.name}
    for key in REQUIRED_META:
        m = re.search(rf"^-\s+\*\*{re.escape(key)}:\*\*\s+(.+)$", text, re.MULTILINE)
        if not m:
            raise ValueError(f"{path.name}: missing '**{key}:**'")
        meta[key] = m.group(1).strip()
    gh_urls = sorted(set(GITHUB_URL_RE.findall(str(meta["GitHub Evidence"]))))
    if not gh_urls:
        raise ValueError(f"{path.name}: must cite >=1 GitHub URL")
    meta["githubUrls"] = gh_urls
    for sec in REQUIRED_SECTIONS:
        if sec not in text:
            raise ValueError(f"{path.name}: missing section '{sec}'")
    dt.date.fromisoformat(str(meta["Date"]))
    return meta


def load_and_validate_adrs(adr_dir: pathlib.Path = ADR_DIR) -> list[dict[str, Any]]:
    files = sorted(adr_dir.glob("ADR-[0-9][0-9][0-9][0-9]-*.md"))
    if len(files) < 6:
        raise ValueError(f"Expected >=6 ADRs, found {len(files)}")
    rows = [parse_adr(p) for p in files]
    for idx, r in enumerate(rows, start=1):
        exp = f"ADR-{idx:04d}"
        if r["id"] != exp:
            raise ValueError(f"Expected {exp}, got {r['id']}")
    return rows


def render_catalog(rows: list[dict[str, Any]]) -> str:
    lines = [
        "# Native Agent Stack Organization ADR Catalog (MADR 4.0 + GitHub Evidence)",
        "",
        "<!-- GENERATED by scripts/architecture_catalog.py; do not edit by hand. -->",
        "",
        f"- **ADR Count:** {len(rows)} Accepted",
        "- **Format:** MADR 4.0 with Mandatory GitHub Primary-Source Evidence",
        f"- **Revisit Threshold:** {REVISIT_DAYS} days",
        "",
        "| ADR | Layer | Title | Status | Date | Grade | GitHub Primary Evidence | Revisit Trigger |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for r in rows:
        gh_links = ", ".join(f"[{u.split('github.com/', 1)[1]}]({u})" for u in r["githubUrls"][:3])
        lines.append(
            f"| [{r['id']}]({r['file']}) | {r['Layer']} | {r['title']} | {r['Status']} | {r['Date']} | "
            f"{r['Evidence Grade']} | {gh_links} | {r['Revisit Trigger']} |"
        )
    lines.append("")
    return "\n".join(lines)


def build_manifest_adr_block(rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "format": "MADR-4.0-GitHub-Evidenced",
        "catalogPath": "docs/adr/CATALOG.md",
        "generatorScript": "scripts/architecture_catalog.py",
        "revisitThresholdDays": REVISIT_DAYS,
        "adrCount": len(rows),
        "records": [
            {
                "id": r["id"],
                "layer": r["Layer"],
                "title": r["title"],
                "status": r["Status"],
                "date": r["Date"],
                "evidenceGrade": r["Evidence Grade"],
                "file": f"docs/adr/{r['file']}",
                "githubUrls": r["githubUrls"],
            }
            for r in rows
        ],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sync-manifest", action="store_true")
    args = ap.parse_args()
    rows = load_and_validate_adrs()
    rendered = render_catalog(rows)
    block = build_manifest_adr_block(rows)
    if args.check:
        if not CATALOG_PATH.is_file() or CATALOG_PATH.read_text(encoding="utf-8") != rendered:
            raise SystemExit("CATALOG.md drift detected")
        m = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        if m.get("adrGovernance") != block:
            raise SystemExit("SOTA_WORKFLOW_MANIFEST.json adrGovernance drift detected")
        print(f"PASS: {len(rows)} GitHub-evidenced MADR 4.0 ADRs & manifest verified (0 drift).")
        return 0
    CATALOG_PATH.write_text(rendered, encoding="utf-8")
    if args.sync_manifest and MANIFEST_PATH.is_file():
        m = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        m["adrGovernance"] = block
        MANIFEST_PATH.write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
